# -*- coding: utf-8 -*-
"""Assemble the WordPress plugin from the static build.

The site this goes on carries several sales pages, so the Knack Extra page has
to be one page among many at a path like /knackextra/. A theme governs every
page on a site, which would have restyled the others and taken over the home
page, so this ships as a plugin instead: the active theme stays exactly where
it is, and only the pages you assign a Knack Extra template to are claimed.

The static site in the repository root stays the source of truth for markup.
This slices index.html and policies.html into two self-contained page
templates, rewrites every relative asset path into a plugin URL, swaps the
hand-written order form for the Fluent Forms shortcode, and writes
dist/knack-extra-plugin/ plus a zip ready to upload under Plugins, Add New.

    python tools/build_plugin.py

Nothing here edits the static build, so the GitHub Pages version keeps working
exactly as it does now.
"""

from __future__ import annotations

import re
import shutil
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'wp-plugin' / 'knack-extra'
OUT = ROOT / 'dist' / 'knack-extra-plugin'
ZIP = ROOT / 'dist' / 'knack-extra-plugin.zip'

SLUG = 'knack-extra'

# Folders of assets/ copied into the plugin. reserve/ is deliberately left
# out: it holds the artwork that is held back because the picture itself is
# the claim, and it should not be one careless click away from the Media
# Library.
ASSET_DIRS = ('css', 'fonts', 'img', 'js', 'video')

GENERATED = (
    "GENERATED by tools/build_plugin.py from the static build.\n"
    " * Edit index.html / policies.html and run the script again. Changes made\n"
    " * directly to this file are lost on the next build."
)


def read(p: Path) -> str:
    return p.read_text(encoding='utf-8')


def between(s: str, start: str, end: str, keep: bool = True) -> str:
    i = s.index(start)
    j = s.index(end, i)
    return s[i:j + len(end)] if keep else s[i + len(start):j]


def php_assets(html: str) -> str:
    """assets/img/x.webp -> <?php echo esc_url( ke_asset( 'img/x.webp' ) ); ?>"""
    pattern = re.compile(
        r'assets/((?:' + '|'.join(ASSET_DIRS) + r')/[A-Za-z0-9_\-./]+?)(\?v=[0-9a-f]+)?(?=["\s,])'
    )
    return pattern.sub(
        lambda m: "<?php echo esc_url( ke_asset( '%s' ) ); ?>" % m.group(1),
        html,
    )


def php_links(html: str) -> str:
    """Point the cross-page links at the WordPress permalinks."""
    html = html.replace(
        'href="policies.html',
        'href="<?php echo esc_url( ke_policies_url() ); ?>',
    )
    html = html.replace(
        'href="index.html',
        'href="<?php echo esc_url( ke_sales_url() ); ?>',
    )
    return html


def php_anchors(html: str) -> str:
    """Make in-page anchors work from either page.

    On the sales page these stay "#packages" so the browser scrolls. On the
    policies page they become the sales page URL plus the fragment, so the
    link still lands in the right place. $ke_home is set at the top of each
    generated template.
    """
    keep = {'main', 'doc'}          # a skip link must stay in its own document
    return re.sub(
        r'href="#([a-z0-9\-]+)"',
        lambda m: m.group(0) if m.group(1) in keep
        else 'href="<?php echo $ke_home; ?>#%s"' % m.group(1),
        html,
    )


def strip_order_form(html: str) -> str:
    start = html.index('<form id="order-form"')
    end = html.index('</form>', start) + len('</form>')
    return html[:start] + '<?php ke_order_form(); ?>' + html[end:]


def document(title: str, body_class: str, home_php: str, body: str,
             theme_color: str, preload_poster: bool) -> str:
    """Wrap a body in a complete HTML document.

    These templates render the whole page rather than calling get_header(),
    the way a page builder's canvas template does, because the design carries
    its own header and footer and the site's theme has nothing to contribute
    to it.
    """
    return (
        "<?php\n"
        "/**\n"
        " * %s\n"
        " *\n"
        " * %s\n"
        " *\n"
        " * @package knack-extra\n"
        " */\n"
        "\n"
        "if ( ! defined( 'ABSPATH' ) ) {\n"
        "\texit;\n"
        "}\n"
        "\n"
        "$ke_home = %s;\n"
        "?><!doctype html>\n"
        "<html <?php language_attributes(); ?>>\n"
        "<head>\n"
        "<meta charset=\"<?php bloginfo( 'charset' ); ?>\">\n"
        "<meta name=\"viewport\" content=\"width=device-width,initial-scale=1,viewport-fit=cover\">\n"
        "<meta name=\"theme-color\" content=\"%s\">\n"
        "<link rel=\"icon\" href=\"<?php echo esc_url( ke_asset( 'img/favicon.svg' ) ); ?>\" type=\"image/svg+xml\">\n"
        "<?php wp_head(); ?>\n"
        "</head>\n"
        "<body <?php body_class( '%s' ); ?>>\n"
        "<?php wp_body_open(); ?>\n\n"
        "%s\n\n"
        "<?php wp_footer(); ?>\n"
        "</body>\n"
        "</html>\n"
        % (title, GENERATED, home_php, theme_color, body_class, body)
    )


def build_sales(index_html: str) -> str:
    # One contiguous slice: skip link, header, nav, main, footer, the sticky
    # mobile bar and the support button. It stops where the static page starts
    # loading its own scripts, because WordPress enqueues those instead.
    body = between(index_html, '<a class="skip-link"',
                   '<script src="assets/js/config.js', keep=False)
    body = '<a class="skip-link"' + body.rstrip()

    body = strip_order_form(body)
    body = php_anchors(php_links(php_assets(body)))

    return document(
        'The Knack Extra sales page.',
        'knack-page knack-sales',
        "''",          # this page is its own anchor target
        body,
        '#080A09',
        True,
    )


def build_policies(policies_html: str, index_html: str) -> str:
    head = between(index_html, '<a class="skip-link"', '</nav>\n\n<main id="main">',
                   keep=False)
    head = '<a class="skip-link"' + head + '</nav>'
    head = head.replace(
        '<header class="site-head" id="head">',
        '<header class="site-head" id="head" data-stuck="1" data-always-stuck="1">',
    )

    main = between(policies_html, '<main class="band on-light" id="doc"', '</main>')
    foot = between(index_html, '<footer class="site-foot">', '</footer>')

    body = php_anchors(php_links(php_assets(head + '\n' + main + '\n' + foot)))

    return document(
        'The Knack Extra policies page.',
        'knack-page knack-policies',
        'esc_url( ke_sales_url() )',
        body,
        '#F8F5EE',
        False,
    )


def build_policies_js(policies_html: str) -> str:
    """Lift the inline script out of policies.html into a real file.

    WordPress enqueues scripts; it does not enqueue inline blocks sitting in a
    template. Pulling it out also means it is cached like everything else.
    """
    script = between(policies_html, "<script>\n(function () {", '</script>', keep=False)
    return (
        "/* Knack Extra - policies page.\n"
        "   GENERATED by tools/build_plugin.py from policies.html. Do not edit. */\n"
        "(function () {" + script
    )


def copy_assets() -> None:
    for name in ASSET_DIRS:
        src = ROOT / 'assets' / name
        if not src.is_dir():
            continue
        shutil.copytree(src, OUT / 'assets' / name, dirs_exist_ok=True,
                        ignore=shutil.ignore_patterns('reserve'))


def copy_sources() -> None:
    for item in sorted(SRC.rglob('*')):
        if item.is_dir():
            continue
        dst = OUT / item.relative_to(SRC)
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(item, dst)


def write_zip() -> int:
    ZIP.parent.mkdir(parents=True, exist_ok=True)
    if ZIP.exists():
        ZIP.unlink()
    count = 0
    with zipfile.ZipFile(ZIP, 'w', zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for f in sorted(OUT.rglob('*')):
            if f.is_file():
                z.write(f, Path(SLUG) / f.relative_to(OUT))
                count += 1
    return count


def main() -> None:
    index_html = read(ROOT / 'index.html')
    policies_html = read(ROOT / 'policies.html')

    # OneDrive keeps a handle on folders it is syncing, so a hard rmtree fails
    # here often enough to be annoying. Every file this script emits is
    # overwritten, so clearing what it can is enough.
    if OUT.exists():
        shutil.rmtree(OUT, ignore_errors=True)
    OUT.mkdir(parents=True, exist_ok=True)

    copy_assets()
    copy_sources()

    (OUT / 'templates').mkdir(parents=True, exist_ok=True)
    (OUT / 'templates' / 'sales.php').write_text(build_sales(index_html), encoding='utf-8')
    (OUT / 'templates' / 'policies.php').write_text(
        build_policies(policies_html, index_html), encoding='utf-8')
    (OUT / 'assets' / 'js' / 'policies.js').write_text(
        build_policies_js(policies_html), encoding='utf-8')

    files = write_zip()
    print('plugin  : %s' % OUT)
    print('zip     : %s  (%d files, %.1f KB)' % (ZIP, files, ZIP.stat().st_size / 1024))
    print('install : WordPress admin, Plugins, Add New, Upload Plugin')


if __name__ == '__main__':
    main()
