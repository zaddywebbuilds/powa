"""Assemble the WordPress theme from the static build.

The static site in the repository root stays the source of truth for markup.
This script slices index.html and policies.html into WordPress templates,
rewrites every relative asset path into a theme URL, swaps the hand-written
order form for the Fluent Forms shortcode, and drops the result in
dist/knack-extra/ plus a zip ready to upload under Appearance, Themes.

    python tools/build_theme.py

Nothing here edits the static build, so the GitHub Pages version keeps working
exactly as it does now.
"""

from __future__ import annotations

import re
import shutil
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC_THEME = ROOT / 'wp-theme'
OUT = ROOT / 'dist' / 'knack-extra'
ZIP = ROOT / 'dist' / 'knack-extra.zip'

SLUG = 'knack-extra'

# Folders of assets/ copied into the theme. reserve/ is deliberately left out:
# it holds the artwork that is held back, and it should not be one careless
# click away from being used.
ASSET_DIRS = ('css', 'fonts', 'img', 'js', 'video')

GENERATED = (
    "GENERATED by tools/build_theme.py from the static build.\n"
    " * Edit index.html / policies.html and run the script again. Changes made\n"
    " * directly to this file are lost on the next build."
)


# ---------------------------------------------------------------- helpers --

def read(p: Path) -> str:
    return p.read_text(encoding='utf-8')


def between(s: str, start: str, end: str, keep: bool = True) -> str:
    """Slice from `start` to `end`, including both when keep is True."""
    i = s.index(start)
    j = s.index(end, i)
    return s[i:j + len(end)] if keep else s[i + len(start):j]


def php_assets(html: str) -> str:
    """assets/img/x.webp  ->  <?php echo esc_url( ke_asset( 'img/x.webp' ) ); ?>"""
    pattern = re.compile(r'assets/((?:' + '|'.join(ASSET_DIRS) + r')/[A-Za-z0-9_\-./]+)')
    return pattern.sub(
        lambda m: "<?php echo esc_url( ke_asset( '%s' ) ); ?>" % m.group(1),
        html,
    )


def php_links(html: str) -> str:
    """Point the cross-page links at WordPress permalinks."""
    html = html.replace(
        'href="policies.html',
        'href="<?php echo esc_url( ke_policies_url() ); ?>',
    )
    html = html.replace(
        'href="index.html',
        'href="<?php echo esc_url( home_url( \'/\' ) ); ?>',
    )
    return html


def php_anchors(html: str) -> str:
    """Make in-page anchors work from any page.

    On the front page these stay as "#packages" so the browser scrolls. On any
    other page they become "https://site/#packages" so the link still lands in
    the right place. $ke_home is set at the top of header.php.
    """
    # A skip link must stay inside the current document.
    keep = {'main', 'doc'}
    return re.sub(
        r'href="#([a-z0-9\-]+)"',
        lambda m: m.group(0) if m.group(1) in keep
        else 'href="<?php echo $ke_home; ?>#%s"' % m.group(1),
        html,
    )


def strip_order_form(html: str) -> str:
    """Replace the hand-written order form with the Fluent Forms shortcode."""
    start = html.index('<form id="order-form"')
    end = html.index('</form>', start) + len('</form>')
    return html[:start] + '<?php ke_order_form(); ?>' + html[end:]


def header_doc(title: str) -> str:
    return (
        "<?php\n"
        "/**\n"
        " * %s\n"
        " *\n"
        " * %s\n"
        " *\n"
        " * @package knack-extra\n"
        " */\n" % (title, GENERATED)
    )


# ------------------------------------------------------------- templates ---

def build_header(index_html: str) -> str:
    body = between(index_html, '<a class="skip-link"', '</nav>\n\n<main id="main">', keep=False)
    body = '<a class="skip-link"' + body + '</nav>'
    body = php_anchors(php_links(php_assets(body)))

    # The header sits over a dark hero on the front page and over an ivory
    # document everywhere else, so it starts in its solid state off-home.
    body = body.replace(
        '<header class="site-head" id="head">',
        '<header class="site-head" id="head"'
        '<?php echo is_front_page() ? \'\' : \' data-stuck="1" data-always-stuck="1"\'; ?>>',
    )

    return (
        header_doc('Site header.')
        + "\n$ke_home = is_front_page() ? '' : esc_url( home_url( '/' ) );\n"
        "?><!doctype html>\n"
        "<html <?php language_attributes(); ?>>\n"
        "<head>\n"
        "<meta charset=\"<?php bloginfo( 'charset' ); ?>\">\n"
        "<meta name=\"viewport\" content=\"width=device-width,initial-scale=1,viewport-fit=cover\">\n"
        "<meta name=\"theme-color\" content=\"<?php echo is_front_page() ? '#080A09' : '#F8F5EE'; ?>\">\n"
        "<link rel=\"icon\" href=\"<?php echo esc_url( ke_asset( 'img/favicon.svg' ) ); ?>\" type=\"image/svg+xml\">\n"
        "<?php wp_head(); ?>\n"
        "</head>\n"
        "<body <?php body_class(); ?>>\n"
        "<?php wp_body_open(); ?>\n\n"
        + body + "\n"
    )


def build_footer(index_html: str) -> str:
    body = between(index_html, '<!-- 16 ', '</a>\n\n<script', keep=False)
    body = '<!-- 16 ' + body + '</a>'
    body = php_anchors(php_links(php_assets(body)))

    return (
        header_doc('Site footer.')
        + "$ke_home = is_front_page() ? '' : esc_url( home_url( '/' ) );\n"
        "?>\n\n"
        + body + "\n\n"
        "<?php wp_footer(); ?>\n"
        "</body>\n"
        "</html>\n"
    )


def build_front_page(index_html: str) -> str:
    main = between(index_html, '<main id="main">', '</main>')
    main = strip_order_form(main)
    main = php_links(php_assets(main))

    return (
        header_doc('The sales page.')
        + "\nget_header();\n?>\n"
        + main + "\n"
        "<?php\n"
        "get_footer();\n"
    )


def build_policies(policies_html: str) -> str:
    main = between(policies_html, '<main class="band on-light" id="doc"', '</main>')
    main = php_links(php_assets(main))

    return (
        "<?php\n"
        "/**\n"
        " * Template Name: Policies\n"
        " *\n"
        " * %s\n"
        " *\n"
        " * @package knack-extra\n"
        " */\n"
        "\n"
        "get_header();\n"
        "?>\n" % GENERATED
        + main + "\n"
        "<?php\n"
        "get_footer();\n"
    )


def build_policies_js(policies_html: str) -> str:
    """Lift the inline script out of policies.html into a real file.

    WordPress enqueues scripts; it does not enqueue inline blocks sitting in a
    template. Pulling it out also means it is cached like everything else.
    """
    script = between(policies_html, "<script>\n(function () {", '</script>', keep=False)
    return (
        "/* Knack Extra - policies page.\n"
        "   GENERATED by tools/build_theme.py from policies.html. Do not edit. */\n"
        "(function () {" + script
    )


# ------------------------------------------------------------------ build --

def copy_assets() -> None:
    for name in ASSET_DIRS:
        src = ROOT / 'assets' / name
        if not src.is_dir():
            continue
        dst = OUT / 'assets' / name
        shutil.copytree(src, dst, dirs_exist_ok=True,
                        ignore=shutil.ignore_patterns('reserve'))


def copy_theme_sources() -> None:
    for item in sorted(SRC_THEME.rglob('*')):
        if item.is_dir():
            continue
        rel = item.relative_to(SRC_THEME)
        dst = OUT / rel
        dst.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(item, dst)


def write_zip() -> int:
    ZIP.parent.mkdir(parents=True, exist_ok=True)
    if ZIP.exists():
        ZIP.unlink()
    count = 0
    with zipfile.ZipFile(ZIP, 'w', zipfile.ZIP_DEFLATED, compresslevel=9) as z:
        for f in sorted(OUT.rglob('*')):
            if f.is_file():
                z.write(f, Path(SLUG) / f.relative_to(OUT))
                count += 1
    return count


def main() -> None:
    index_html = read(ROOT / 'index.html')
    policies_html = read(ROOT / 'policies.html')

    # OneDrive keeps a handle on folders it is syncing, so a hard rmtree fails
    # here often enough to be annoying. Clearing what it can and rebuilding
    # over the top is enough: every file this script emits is overwritten.
    if OUT.exists():
        shutil.rmtree(OUT, ignore_errors=True)
    OUT.mkdir(parents=True, exist_ok=True)

    copy_assets()
    copy_theme_sources()

    (OUT / 'header.php').write_text(build_header(index_html), encoding='utf-8')
    (OUT / 'footer.php').write_text(build_footer(index_html), encoding='utf-8')
    (OUT / 'front-page.php').write_text(build_front_page(index_html), encoding='utf-8')
    (OUT / 'page-policies.php').write_text(build_policies(policies_html), encoding='utf-8')
    (OUT / 'assets' / 'js' / 'policies.js').write_text(
        build_policies_js(policies_html), encoding='utf-8'
    )

    files = write_zip()
    size = ZIP.stat().st_size

    print('theme   : %s' % OUT)
    print('zip     : %s  (%d files, %.1f KB)' % (ZIP, files, size / 1024))
    print('install : WordPress admin, Appearance, Themes, Add New, Upload Theme')


if __name__ == '__main__':
    main()
